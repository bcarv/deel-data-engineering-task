-- analytics.orders_status_history (idempotent, append-only).
-- One row per status change. PK is the event id, not order_id. No physical FKs.

CREATE TABLE IF NOT EXISTS analytics.orders_status_history (
    history_id        BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    order_id          BIGINT        NOT NULL,
    previous_status   VARCHAR,
    status            VARCHAR,
    changed_at        TIMESTAMP(3)  NOT NULL,
    source_ts_ms      BIGINT,
    op                CHAR(1),
    ingested_at       TIMESTAMP(3)  DEFAULT CURRENT_TIMESTAMP(3),
    PRIMARY KEY (history_id)
);

CREATE INDEX IF NOT EXISTS idx_orders_status_history_order_changed
    ON analytics.orders_status_history (order_id, changed_at);
